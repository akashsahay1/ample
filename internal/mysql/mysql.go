func slash(p string) string { return filepath.ToSlash(p) }

func binPath(name string) string { return filepath.Join(paths.MySQLDir(), "bin", paths.Exe(name)) }

// MysqldPath is the server executable.
func MysqldPath() string { return binPath("mysqld") }

// IniPath is <Home>/conf/my.ini.
func IniPath() string { return filepath.Join(paths.ConfDir(), "my.ini") }

// LogPath is the MySQL error log (log-error in my.ini). Use a different file
// (e.g. logs/mysql-console.log) for services.Start's stdout/stderr capture.
func LogPath() string { return filepath.Join(paths.LogsDir(), "mysql.log") }

// StartArgs runs mysqld in the foreground with the AMPLS config.
func StartArgs() []string { return []string{"--defaults-file=" + slash(IniPath())} }

// RenderIni is the pure my.ini renderer.
func RenderIni(port int, home string) string {
	j := func(p ...string) string { return slash(filepath.Join(append([]string{home}, p...)...)) }
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("# Generated by AMPLS - do not edit; changes are overwritten.")
	w("[mysqld]")
	w("basedir=%q", j("mysql"))
	w("datadir=%q", j("data", "mysql"))
	w("port=%d", port)
	w("bind-address=127.0.0.1")
	w("mysqlx=OFF")
	w("log-error=%q", j("logs", "mysql.log"))
	w("pid-file=%q", j("run", "mysqld-internal.pid"))
	w("tmpdir=%q", j("tmp"))
	w("character-set-server=utf8mb4")
	w("collation-server=utf8mb4_0900_ai_ci")
	w("max_allowed_packet=256M")
	w("innodb_buffer_pool_size=256M")
	w("innodb_redo_log_capacity=128M")
	w("max_connections=200")
	w("sql_mode=ONLY_FULL_GROUP_BY,STRICT_TRANS_TABLES,NO_ZERO_IN_DATE,NO_ZERO_DATE,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION")
	w("")
	w("[client]")
	w("port=%d", port)
	w("host=127.0.0.1")
	w("default-character-set=utf8mb4")
	return b.String()
}

// WriteConfig writes conf/my.ini.
func WriteConfig(port int) error {
	if port <= 0 {
		port = 3306
	}
	for _, d := range []string{paths.ConfDir(), paths.LogsDir(), paths.RunDir(), paths.TmpDir()} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			return fmt.Errorf("mysql: write config: %w", err)
		}
	}
	if err := os.WriteFile(IniPath(), []byte(RenderIni(port, paths.Home())), 0o644); err != nil {
		return fmt.Errorf("mysql: write config: %w", err)
	}
	return nil
}

// Initialized reports whether the datadir holds an initialized server.
func Initialized() bool {
	for _, p := range []string{"mysql.ibd", "mysql"} {
		if _, err := os.Stat(filepath.Join(paths.MySQLDataDir(), p)); err == nil {
			return true
		}
	}
	return false
}

// Initialize runs mysqld --initialize-insecure (root@localhost, empty password).
func Initialize() error {
	if Initialized() {
		return nil
	}
	if _, err := os.Stat(IniPath()); err != nil {
		if err := WriteConfig(3306); err != nil {
			return err
		}
	}
	// datadir must be absent or empty
	if entries, err := os.ReadDir(paths.MySQLDataDir()); err == nil && len(entries) > 0 {
		return fmt.Errorf("mysql: initialize: %s is not empty", paths.MySQLDataDir())
	}
	os.Remove(paths.MySQLDataDir())
	if err := os.MkdirAll(paths.DataDir(), 0o755); err != nil {
		return fmt.Errorf("mysql: initialize: %w", err)
	}
	// Initialize into a staging dir and rename on success, so an interrupted
	// init never leaves a half-built datadir that looks initialized.
	stage := paths.MySQLDataDir() + ".init"
	os.RemoveAll(stage)
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, MysqldPath(), "--defaults-file="+slash(IniPath()), "--datadir="+slash(stage), "--initialize-insecure", "--console")
	cmd.Dir = filepath.Dir(MysqldPath())
	services.Hide(cmd)
	out, err := cmd.CombinedOutput()
	if err != nil {
		os.RemoveAll(stage)
		return fmt.Errorf("mysql: initialize: %v: %s", err, lastLines(string(out), 10))
	}
	if _, err := os.Stat(filepath.Join(stage, "mysql.ibd")); err != nil {
		os.RemoveAll(stage)
		return fmt.Errorf("mysql: initialize: datadir not created: %s", lastLines(string(out), 10))
	}
	if err := os.Rename(stage, paths.MySQLDataDir()); err != nil {
		return fmt.Errorf("mysql: initialize: %w", err)
	}
	if !Initialized() {
		return fmt.Errorf("mysql: initialize: datadir not created: %s", lastLines(string(out), 10))
	}
	return nil
}

var versionRe = regexp.MustCompile(`Ver\s+([0-9]+\.[0-9]+\.[0-9]+)`)

// Version returns the mysqld version ("8.4.11") or "".
func Version() string {
	if _, err := os.Stat(MysqldPath()); err != nil {
		return ""
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, MysqldPath(), "--version")
	services.Hide(cmd)
	out, _ := cmd.CombinedOutput()
	if m := versionRe.FindSubmatch(out); m != nil {
		return string(m[1])
	}
	return ""
}

// InstallFromZip extracts the MySQL winx64 zip into paths.MySQLDir().
func InstallFromZip(zipPath string) error {
	dir := paths.MySQLDir()
	stage := dir + ".staging"
	os.RemoveAll(stage)
	if err := download.Unzip(zipPath, stage, true); err != nil {
		os.RemoveAll(stage)
		return fmt.Errorf("mysql: install: %w", err)
	}
	if _, err := os.Stat(filepath.Join(stage, "bin", paths.Exe("mysqld"))); err != nil {
		os.RemoveAll(stage)
		return fmt.Errorf("mysql: install: mysqld not found in %s", filepath.Base(zipPath))
	}
	if _, err := os.Stat(dir); err == nil {
		old := dir + ".old"
		os.RemoveAll(old)
		if err := os.Rename(dir, old); err != nil {
			os.RemoveAll(stage)
			return fmt.Errorf("mysql: install (is MySQL running?): %w", err)
		}
		defer os.RemoveAll(old)
	}
	if err := os.Rename(stage, dir); err != nil {
		return fmt.Errorf("mysql: install: %w", err)
	}
	return nil
}

