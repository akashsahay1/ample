func ensureWelcome() error {
	p := filepath.Join(paths.WWWDir(), "index.php")
	if _, err := os.Stat(p); err == nil {
		return nil
	}
	if err := os.WriteFile(p, []byte(welcomePHP), 0o644); err != nil {
		return fmt.Errorf("apache: write welcome page: %w", err)
	}
	return nil
}
